// In-memory knowledge store with backfill & feedback persistence
let knowledgeEntries: KnowledgeBaseEntry[] = [...SEEDED_KNOWLEDGE_BASE];

export function getKnowledgeEntries(): KnowledgeBaseEntry[] {
  return [...knowledgeEntries];
}

export function getKnowledgeBaseCount(): number {
  return knowledgeEntries.length;
}

export function getLatestKnowledgeDate(): string {
  if (knowledgeEntries.length === 0) return 'None';
  const latest = [...knowledgeEntries].sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime())[0];
  return new Date(latest.createdAt).toLocaleDateString([], { month: 'short', day: 'numeric', year: 'numeric' });
}

export function addKnowledgeEntry(entry: Omit<KnowledgeBaseEntry, 'id' | 'createdAt' | 'helpfulVotes' | 'unhelpfulVotes'>): KnowledgeBaseEntry {
  const newEntry: KnowledgeBaseEntry = {
    ...entry,
    id: `kb-${Date.now()}`,
    helpfulVotes: 0,
    unhelpfulVotes: 0,
    createdAt: new Date().toISOString(),
  };

  knowledgeEntries = [newEntry, ...knowledgeEntries];
  return newEntry;
}

export function recordFeedback(id: string, helpful: boolean): void {
  const entry = knowledgeEntries.find(e => e.id === id);
  if (!entry) return;
  if (helpful) {
    entry.helpfulVotes += 1;
  } else {
    entry.unhelpfulVotes += 1;
    // Student or tech rejection lowers reliability
    if (entry.unhelpfulVotes >= 3 && entry.unhelpfulVotes > entry.helpfulVotes) {
      entry.isReliable = false;
    }
  }
}
